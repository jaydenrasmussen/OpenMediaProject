#!/usr/bin/env python3
"""Extracts Sonarr's title-parsing regexes into crates/omp-parser/src/tv_patterns.rs.

Usage: gen_tv_patterns.py <path to sonarr checkout>

The patterns are copied verbatim (they are .NET regexes and run on `netre`), so
the Rust port tracks upstream exactly. Re-run after updating the reference clone.
"""
import re
import sys
from pathlib import Path

root = Path(sys.argv[1])
parser_cs = (root / "src/NzbDrone.Core/Parser/Parser.cs").read_text()
common_cs = (root / "src/NzbDrone.Core/Parser/ParserCommon.cs").read_text()


def verbatim(text, i):
    """Reads a C# verbatim string starting at text[i] == '@' and returns (value, next index)."""
    assert text[i] == "@" and text[i + 1] == '"', text[i : i + 20]
    j = i + 2
    out = []
    while True:
        if text[j] == '"':
            if text[j + 1] == '"':
                out.append('"')
                j += 2
                continue
            return "".join(out), j + 1
        out.append(text[j])
        j += 1


def plain(text, i):
    """Reads a normal C# string literal at text[i] == '"'."""
    assert text[i] == '"'
    j = i + 1
    out = []
    while text[j] != '"':
        if text[j] == "\\":
            out.append(text[j + 1])
            j += 2
            continue
        out.append(text[j])
        j += 1
    return "".join(out), j + 1


def regexes(block, replace_by_default=False):
    """Yields (pattern, replacement|None, ignore_case) for every active `new Regex(`/`new RegexReplace(` in block."""
    found = []
    for m in re.finditer(r"new(?: Regex| RegexReplace)?\(", block):
        line_start = block.rfind("\n", 0, m.start()) + 1
        if block[line_start : m.start()].strip().startswith("//"):
            continue
        i = m.end()
        while block[i].isspace():
            i += 1
        head = block[m.start() : m.end()]
        is_replace = head.startswith("new RegexReplace") or (head == "new(" and replace_by_default)
        pattern, i = verbatim(block, i)
        replacement = None
        if is_replace:
            i = block.index(",", i) + 1
            while block[i].isspace():
                i += 1
            if block.startswith("string.Empty", i):
                replacement, i = "", i + len("string.Empty")
            else:
                replacement, i = plain(block, i)
        tail = block[i : block.index(";", i)] if ";" in block[i : i + 600] else block[i : i + 300]
        tail = tail.split("),")[0].split(");")[0]
        found.append((pattern, replacement, "IgnoreCase" in tail))
    return found


def array_block(text, name):
    start = text.index(name)
    start = text.index("{", text.index("=", start))
    depth = 0
    for k in range(start, len(text)):
        if text[k] == "{":
            depth += 1
        elif text[k] == "}":
            depth -= 1
            if depth == 0:
                return text[start : k + 1]
    raise SystemExit("unterminated " + name)


def single(text, name):
    start = text.index(name)
    declaration = text[text.rfind("\n", 0, start) : start]
    return regexes(text[start : text.index(";", start)], "RegexReplace" in declaration)[0]


def raw(s):
    h = "#"
    while ('"' + h) in s:
        h += "#"
    return f'r{h}"{s}"{h}'


out = []
out.append("//! Generated by scripts/gen_tv_patterns.py from Sonarr's Parser.cs and ParserCommon.cs")
out.append("//! (GPL-3.0). Do not edit by hand; re-run the script instead.\n")


def emit_array(const, items, with_replacement=False):
    if with_replacement:
        out.append(f"pub const {const}: &[(&str, &str, bool)] = &[")
        for p, r, ci in items:
            out.append(f"    ({raw(p)}, {raw(r)}, {str(ci).lower()}),")
    else:
        out.append(f"pub const {const}: &[(&str, bool)] = &[")
        for p, _, ci in items:
            out.append(f"    ({raw(p)}, {str(ci).lower()}),")
    out.append("];\n")


def emit_one(const, item):
    out.append(f"pub const {const}: (&str, bool) = ({raw(item[0])}, {str(item[2]).lower()});\n")


emit_array("REPORT_TITLE", regexes(array_block(parser_cs, "ReportTitleRegex = ")))
emit_array("SPECIAL_EPISODE_TITLE", regexes(array_block(parser_cs, "SpecialEpisodeTitleRegex = ")))
emit_array("REJECT_HASHED", regexes(array_block(parser_cs, "RejectHashedReleasesRegexes = ")))
emit_array("SEASON_FOLDERS", regexes(array_block(parser_cs, "SeasonFolderRegexes = ")))
emit_array("PRE_SUBSTITUTION", regexes(array_block(common_cs, "PreSubstitutionRegex = ")), True)
emit_array("PATH_PRE_SUBSTITUTION", regexes(array_block(common_cs, "PathPreSubstitutionRegex = ")), True)

for const, name, text in [
    ("REVERSED_TITLE", "ReversedTitleRegex =", parser_cs),
    ("ANIME_SEASON_RELEASE_METADATA", "AnimeSeasonReleaseMetadataRegex =", parser_cs),
    ("ANIME_SPECIAL_MARKER", "AnimeSpecialMarkerRegex =", parser_cs),
    ("NORMALIZE", "NormalizeRegex =", parser_cs),
    ("PERCENT", "PercentRegex =", parser_cs),
    ("SIMPLE_TITLE", "SimpleTitleRegex =", parser_cs),
    ("SIX_DIGIT_AIR_DATE", "SixDigitAirDateRegex =", parser_cs),
    ("CLEAN_QUALITY_BRACKETS", "CleanQualityBracketsRegex =", parser_cs),
    ("YEAR_IN_TITLE", "YearInTitleRegex =", parser_cs),
    ("TITLE_COMPONENTS", "TitleComponentsRegex =", parser_cs),
    ("PART", "PartRegex =", parser_cs),
    ("PUNCTUATION", "PunctuationRegex =", parser_cs),
    ("ARTICLE_WORD", "ArticleWordRegex =", parser_cs),
    ("DUPLICATE_SPACES", "DuplicateSpacesRegex =", parser_cs),
    ("SEASON_FOLDER", "SeasonFolderRegex =", parser_cs),
    ("SIMPLE_EPISODE_NUMBER", "SimpleEpisodeNumberRegex =", parser_cs),
    ("REQUEST_INFO", "RequestInfoRegex =", parser_cs),
    ("MULTI", "MultiRegex =", parser_cs),
    ("WEBSITE_PREFIX", "WebsitePrefixRegex =", common_cs),
    ("WEBSITE_POSTFIX", "WebsitePostfixRegex =", common_cs),
    ("CLEAN_TORRENT_SUFFIX", "CleanTorrentSuffixRegex =", common_cs),
]:
    emit_one(const, single(text, name))

Path(sys.argv[2] if len(sys.argv) > 2 else "crates/omp-parser/src/tv_patterns.rs").write_text("\n".join(out))
