for fixture, kinds in wanted.items():
    table = methods(root / f"{fixture}.cs")
    for method, kind in kinds.items():
        cases = table.get(method)
        if cases is None:
            print("missing", fixture, method, file=sys.stderr)
            continue
        const = f"{kind}_{method}".upper()
        out.append(f"const {const}: &[&[Arg]] = &[")
        for c in cases:
            parts = []
            for v in c:
                if isinstance(v, str):
                    parts.append(f"Arg::S({rust(v)})")
                elif isinstance(v, list):
                    parts.append(f"Arg::L({rust(v)})")
                elif isinstance(v, bool):
                    parts.append(f"Arg::B({rust(v)})")
                elif isinstance(v, float):
                    parts.append(f"Arg::F({rust(v)})")
                elif v is None:
                    parts.append("Arg::N")
                else:
                    parts.append(f"Arg::I({v})")
            out.append("    &[" + ", ".join(parts) + "],")
        out.append("];")
        out.append("")

target = Path(sys.argv[2] if len(sys.argv) > 2 else "crates/omp-parser/tests/tv_fixtures/data.rs")
target.write_text("\n".join(out))
