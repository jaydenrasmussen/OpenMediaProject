def decode(text, i):
    """Reads one C# literal from text[i:]; returns (python value, next index)."""
    while text[i] in " \t\n":
        i += 1
    if text.startswith('@"', i):
        j = i + 2
        out = []
        while True:
            if text[j] == '"':
                if text[j + 1] == '"':
                    out.append('"')
                    j += 2
                    continue
                return "".join(out), j + 1
            out.append(text[j])
            j += 1
    if text[i] == '"':
        j = i + 1
        out = []
        while text[j] != '"':
            if text[j] == "\\":
                n = text[j + 1]
                if n == "u":
                    out.append(chr(int(text[j + 2 : j + 6], 16)))
                    j += 6
                    continue
                out.append({"n": "\n", "t": "\t"}.get(n, n))
                j += 2
                continue
            out.append(text[j])
            j += 1
        return "".join(out), j + 1
    m = re.match(r"new\s*(?:int)?\[\]\s*\{([^}]*)\}", text[i:])
    if m:
        nums = [int(x) for x in m.group(1).replace(" ", "").split(",") if x]
        return nums, i + m.end()
    m = re.match(r"-?\d+(?:\.\d+)?m?", text[i:])
    if m:
        v = m.group(0).rstrip("m")
        return (float(v) if "." in v else int(v)), i + m.end()
    if text.startswith("null", i):
        return None, i + 4
    if text.startswith("true", i):
        return True, i + 4
    if text.startswith("false", i):
        return False, i + 5
    raise ValueError(text[i : i + 40])


def args(text, i):
    """Parses `(a, b, c)` starting after the opening parenthesis."""
    out = []
    while True:
        v, i = decode(text, i)
        out.append(v)
        while text[i] in " \t\n":
            i += 1
        if text[i] == ",":
            i += 1
            continue
        assert text[i] == ")", text[i : i + 30]
        return out


def methods(path):
    text = path.read_text()
    found = {}
    pending = []
    for line in text.split("\n"):
        s = line.strip()
        if s.startswith("//"):
            continue
        if s.startswith("[TestCase("):
            try:
                pending.append(args(s, len("[TestCase(")))
            except (ValueError, AssertionError, IndexError):
                pass
            continue
        m = re.match(r"public void (\w+)\(", s)
        if m:
            found[m.group(1)] = pending
            pending = []
        elif s.startswith("[Test"):
            pass
        elif s and not s.startswith("[") and not s.startswith("{") and not s.startswith("}"):
            pending = [] if "TestCase" not in s else pending
    return found


def raw(s):
    h = "#"
    while ('"' + h) in s:
        h += "#"
    return f'r{h}"{s}"{h}'


def rust(v):
    if isinstance(v, str):
        return raw(v)
    if isinstance(v, list):
        return "&[" + ", ".join(str(x) for x in v) + "]"
    if isinstance(v, bool):
        return str(v).lower()
    if isinstance(v, float):
        return repr(v)
    return str(v)


