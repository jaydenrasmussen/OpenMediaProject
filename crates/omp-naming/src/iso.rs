/// Two-letter code (lower case) for a code in any of the usual forms
/// ("en", "en-US", "eng", "fre"), or `None` when it is not recognised.
pub(crate) fn two_letter(code: &str) -> Option<&'static str> {
    let lower = code.trim().to_lowercase();
    let base = lower.split(['-', '_']).next().unwrap_or("");
    if base.len() == 2 {
        return THREE_TO_TWO
            .iter()
            .map(|(_, two)| *two)
            .find(|two| *two == base);
    }
    let t = BT.iter().find(|(b, _)| *b == base).map_or(base, |(_, t)| t);
    THREE_TO_TWO
        .iter()
        .find(|(three, _)| *three == t)
        .map(|(_, two)| *two)
}

/// Whether `code` is a two-letter language code we know ("fr", not "jp").
pub(crate) fn is_known_two_letter(code: &str) -> bool {
    code.len() == 2 && two_letter(code).is_some()
}
